# 元组与列表的最大区别在于元组不可以更改，所以可看作 只读的列表
# 元组的定义使用小括号
a=('abc',4,'a',None)
print(a)
print('-'*30)

#空元组的定义
b=()
print(b)

# 注意：如果元组仅有一个元素，在元素后要加上一个逗号，否则不会被认为是元组类型
b=('a',)

#虽然元组是不可以更改的，但是拥有索引
# index 查找方法：
index=a.index(4)
print(f'4在a中的索引为{index}')

#统计某个数据在元组中出现的次数：
a=(1,564,1,548,1)
times=a.count(1)
print(f'1在元组a中出现{times}次')

#统计元组中元素的个数
length=len(a)
print(f"a元组中元素个数为{length}个")

#遍历与list都相同
#  需要注意的是  元组无法更改，但是如果，元组内嵌套了一个list，这时list内的数据是可以更改的


