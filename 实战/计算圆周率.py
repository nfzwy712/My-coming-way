#根据泰勒级数关系式，求圆周率的值。当最后一项的值小于给定的阈值时结束。输出到小数点后六位

# 使用 float() 安全地获取用户输入的阈值
threshold = float(input("输入小于1且大于0的阈值"))

pi_4 = 0      # 用于累加 π/4 的值
k = 0         # 计数器，用于生成分母 (2*k+1)
f = 1         # 符号变量，初始为1，每次循环取反实现正负交替

# 当当前项的绝对值大于等于阈值时，继续累加
while abs(f * 1 / (2 * k + 1)) >= threshold:
    pi_4 = pi_4 + f * 1 / (2 * k + 1)
    k = k + 1      # 计数器加1，准备计算下一项的分母
    f = -f         # 改变正负号

# 输出结果，精确到小数点后6位
print("{:.6f}".format(pi_4 * 4))