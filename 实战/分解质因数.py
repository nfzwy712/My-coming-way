# 分解质因数只针对合数(非质数或者非素数，不包括1在内)，每个合数都可以写成几个质数相乘的形式，其中每个质数都是这个合数的因数，叫做这个合数的分解质因数。
n = int(input("输入一个正整数: "))
rs = []
# 先处理2，先处理2是因为2是唯一的偶数质数，当我们反复除以2，那么我们就可以排除以后的偶数，优化了代码
while n % 2 == 0:
    rs.append(2)
    n //= 2
# 从3开始只检查奇数
i = 3
while i * i <= n:
    while n % i == 0:
        rs.append(i)
        n //= i
    i += 2  # 只检查奇数
# 剩余的n如果大于2，说明是质因数
if n > 2:
    rs.append(n)
print(f"质因数分解结果: {' × '.join(map(str, rs))}")

